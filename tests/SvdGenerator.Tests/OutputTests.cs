using System;
using System.IO;
using System.Linq;
using Xunit;
using static SvdGenerator.Tests.Svd;

namespace SvdGenerator.Tests
{
    public class OutputTests
    {
        const string Notice = "<!--\nCopyright (c) 2025 Vendor.\n\n SPDX-License-Identifier: Apache-2.0\n-->\n";

        static string SimpleDevice(string peripheral = "P") => Device(Peripheral(peripheral, 0x1000, SimpleRegister(), extra: Irq));

        static (int Code, string Error) Run(TempDirectory input, string svd, string output, params string[] options)
        {
            var path = input.Write("device.svd", svd);
            var error = new StringWriter();
            var code = Program.Run(new[] { path, output }.Concat(options).ToArray(), new StringWriter(), error);
            return (code, error.ToString());
        }

        [Fact]
        public void Every_file_starts_with_the_banner()
        {
            var files = Generate(Device(Peripheral("P", 0x1000, SimpleRegister(), extra: Irq), prolog: Notice));

            foreach (var content in files.Where(f => f.Key.EndsWith(".hpp", StringComparison.Ordinal) && f.Key != Emitter.RegistersFile).Select(f => f.Value))
            {
                Assert.StartsWith(
                    "// Generated by SvdGenerator 1.2.3; do not edit.\n" +
                    "// Source: test.svd (device DEV, version 1.0)\n" +
                    "// SHA-256: 0123abcd\n" +
                    "//\n" +
                    "// What this file takes from the source file (names, addresses, descriptions)\n" +
                    "// remains under the notice that file carries:\n" +
                    "//\n" +
                    "//   Copyright (c) 2025 Vendor.\n" +
                    "//\n" +
                    "//   SPDX-License-Identifier: Apache-2.0\n" +
                    "//\n" +
                    "// SvdGenerator puts no license of its own on the code it generates around it.\n" +
                    "\n", content, StringComparison.Ordinal);
            }
        }

        [Fact]
        public void A_source_without_notice_gives_a_banner_that_claims_nothing()
        {
            var header = GenerateOne(Peripheral("P", 0x1000, SimpleRegister()));

            Assert.StartsWith(
                "// Generated by SvdGenerator 1.2.3; do not edit.\n" +
                "// Source: test.svd (device DEV, version 1.0)\n" +
                "// SHA-256: 0123abcd\n" +
                "\n" +
                "// Map of this file", header, StringComparison.Ordinal);
            Assert.DoesNotContain("license", header[..header.IndexOf("#pragma once", StringComparison.Ordinal)], StringComparison.OrdinalIgnoreCase);
        }

        [Fact]
        public void The_register_building_blocks_are_written_with_the_headers()
        {
            var files = Generate(Device(Peripheral("P", 0x1000, SimpleRegister()), prolog: Notice));
            var registers = files[Emitter.RegistersFile];

            // Generated, so the generator replaces it; but not derived from the
            // SVD, so it carries its own license and not the vendor's notice.
            Assert.StartsWith("// Generated by SvdGenerator 1.2.3; do not edit.\n\n/**\n", registers, StringComparison.Ordinal);
            Assert.DoesNotContain("Vendor", registers);
            Assert.DoesNotContain("test.svd", registers);
            Assert.Contains("The MIT License (MIT)", registers);
            Assert.Contains("#ifndef SVDGENERATOR_MMIO_HPP\n#define SVDGENERATOR_MMIO_HPP\n", registers);
            Assert.Contains("\nnamespace mmio\n{\n", registers);
            Assert.DoesNotContain("opsy::", registers);

            Assert.Contains("\n#pragma once\n\n#include \"mmio.hpp\"\n\nnamespace DEV\n{\n", files["p.hpp"]);
            Assert.DoesNotContain("memory.hpp", files["p.hpp"]);
        }

        [Fact]
        public void The_register_building_blocks_are_the_same_for_every_device()
        {
            var one = Generate(Device(Peripheral("P", 0x1000, SimpleRegister()), name: "ONE"));
            var other = Generate(Device(Peripheral("Q", 0x2000, SimpleRegister("X")), name: "OTHER", prolog: Notice));

            Assert.Equal(one[Emitter.RegistersFile], other[Emitter.RegistersFile]);
        }

        [Fact]
        public void The_license_text_element_is_part_of_the_notice()
        {
            var files = Generate(Device(Peripheral("P", 0x1000, SimpleRegister()), extra: "<licenseText>First line\\nSecond line</licenseText>"));

            Assert.Contains("//   First line\n//   Second line\n", files["p.hpp"]);
        }

        [Fact]
        public void Line_endings_are_lf_on_every_platform()
        {
            foreach (var content in Generate(SimpleDevice()).Values)
            {
                Assert.DoesNotContain('\r', content);
                Assert.EndsWith("\n", content, StringComparison.Ordinal);
            }
        }

        [Fact]
        public void The_namespace_is_a_valid_identifier()
        {
            var header = Generate(Device(Peripheral("P", 0x1000, SimpleRegister()), name: "my-dev 1"))["p.hpp"];

            Assert.Contains("\nnamespace MY_DEV_1\n", header);
        }

        [Fact]
        public void A_name_starting_with_a_digit_is_prefixed()
        {
            var header = GenerateOne(Peripheral("P", 0x1000, Register("2X", 0, Field("3F", 0, 1))));

            Assert.Contains("class _2x_r {", header);
            Assert.Contains("class _3f_f {", header);
            Assert.Contains("constexpr auto _3f() const", header);
            Assert.Contains("> _2x;", header);
        }

        [Fact]
        public void A_description_cannot_close_the_comment()
        {
            var header = GenerateOne(Peripheral("P", 0x1000, Register("R", 0, "<field><name>F</name><description>a */ b</description><bitOffset>0</bitOffset><bitWidth>1</bitWidth></field>")));

            Assert.Contains(" * a * / b\n", header);
        }

        [Fact]
        public void Files_that_were_not_generated_are_left_alone()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            output.Write("memory.hpp", "// opsy\n");
            output.Write("CMakeLists.txt", "add_library(x INTERFACE)\n");
            output.Write("device.ld", "MEMORY {}\n");

            var (code, error) = Run(input, SimpleDevice(), output.Path);

            Assert.Equal((Program.ExitOk, ""), (code, error));
            Assert.Equal(new[] { "CMakeLists.txt", "README.md", "device.hpp", "device.ld", "interrupts.hpp", "memory.hpp", "mmio.hpp", "p.hpp", "vectors.hpp" }, output.Names());
            Assert.Equal("// opsy\n", File.ReadAllText(output.File("memory.hpp")));
        }

        [Fact]
        public void Generated_files_that_are_no_longer_produced_are_removed()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            Run(input, SimpleDevice("OLD"), output.Path);
            Assert.Contains("old.hpp", output.Names());

            Run(input, SimpleDevice("NEW"), output.Path);

            Assert.Equal(new[] { "README.md", "device.hpp", "interrupts.hpp", "mmio.hpp", "new.hpp", "vectors.hpp" }, output.Names());
        }

        [Fact]
        public void Headers_written_before_the_banner_existed_are_recognised()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            const string legacy = "#pragma once\n\n#if __has_include(\"memory.hpp\")\n#include \"memory.hpp\"\n#else\n#include <utility/memory.hpp>\n#endif\n\nnamespace DEV\n{\n}\n";
            output.Write("p.hpp", legacy.Replace("\n", "\r\n"));
            output.Write("gone.hpp", legacy);
            output.Write("interrupts.hpp", "#pragma once\n\n#include <cstddef>\n\nconstexpr std::size_t irq_count = 4;\n");

            var (code, _) = Run(input, SimpleDevice(), output.Path);

            Assert.Equal(Program.ExitOk, code);
            Assert.Equal(new[] { "README.md", "device.hpp", "interrupts.hpp", "mmio.hpp", "p.hpp", "vectors.hpp" }, output.Names());
            Assert.StartsWith(Emitter.BannerStart, File.ReadAllText(output.File("p.hpp")), StringComparison.Ordinal);
        }

        [Fact]
        public void A_file_of_the_same_name_that_was_not_generated_is_not_overwritten()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            output.Write("p.hpp", "// written by hand\n");

            var (code, error) = Run(input, SimpleDevice(), output.Path);

            Assert.Equal(Program.ExitRefused, code);
            Assert.Contains("Refusing to overwrite", error);
            Assert.Equal(new[] { "p.hpp" }, output.Names());
            Assert.Equal("// written by hand\n", File.ReadAllText(output.File("p.hpp")));

            (code, _) = Run(input, SimpleDevice(), output.Path, "--force");

            Assert.Equal(Program.ExitOk, code);
            Assert.StartsWith(Emitter.BannerStart, File.ReadAllText(output.File("p.hpp")), StringComparison.Ordinal);
        }

        [Fact]
        public void A_failure_leaves_the_directory_as_it_was()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            Run(input, SimpleDevice(), output.Path);
            var before = File.ReadAllText(output.File("p.hpp"));

            var (code, error) = Run(input, Device(Peripheral("P", 0x1000, Register("R", 0, Field("F", 0, 1), size: "24"))), output.Path);

            Assert.Equal(Program.ExitError, code);
            Assert.Contains("24 bits", error);
            Assert.DoesNotContain("   at ", error);
            Assert.Equal(new[] { "README.md", "device.hpp", "interrupts.hpp", "mmio.hpp", "p.hpp", "vectors.hpp" }, output.Names());
            Assert.Equal(before, File.ReadAllText(output.File("p.hpp")));
        }

        [Fact]
        public void An_up_to_date_file_is_not_rewritten()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            Run(input, SimpleDevice(), output.Path);
            var stamp = new DateTime(2020, 1, 2, 3, 4, 5, DateTimeKind.Utc);
            File.SetLastWriteTimeUtc(output.File("p.hpp"), stamp);

            Run(input, SimpleDevice(), output.Path);

            Assert.Equal(stamp, File.GetLastWriteTimeUtc(output.File("p.hpp")));
        }

        [Fact]
        public void The_output_directory_is_created()
        {
            using var input = new TempDirectory();
            using var parent = new TempDirectory();
            var output = Path.Combine(parent.Path, "a", "b");

            var (code, _) = Run(input, SimpleDevice(), output);

            Assert.Equal(Program.ExitOk, code);
            Assert.True(File.Exists(Path.Combine(output, "p.hpp")));
        }

        [Fact]
        public void Check_passes_on_what_was_just_generated_whatever_the_line_endings()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            Run(input, SimpleDevice(), output.Path);
            output.Write("memory.hpp", "// opsy\n");
            File.WriteAllText(output.File("p.hpp"), File.ReadAllText(output.File("p.hpp")).Replace("\n", "\r\n"));

            var (code, error) = Run(input, SimpleDevice(), output.Path, "--check");

            Assert.Equal((Program.ExitOk, ""), (code, error));
        }

        [Fact]
        public void Check_reports_what_differs_and_writes_nothing()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            Run(input, SimpleDevice("OLD"), output.Path);
            File.AppendAllText(output.File("interrupts.hpp"), "// edited\n");
            var before = output.Names();

            var (code, error) = Run(input, SimpleDevice("NEW"), output.Path, "--check");

            Assert.Equal(Program.ExitOutOfDate, code);
            Assert.Contains("interrupts.hpp: differs", error);
            Assert.Contains("new.hpp: missing", error);
            Assert.Contains("old.hpp: no longer generated", error);
            Assert.Equal(before, output.Names());
        }

        [Fact]
        public void A_missing_input_is_an_error()
        {
            using var output = new TempDirectory();

            var error = new StringWriter();
            var code = Program.Run(new[] { Path.Combine(output.Path, "nope.svd"), output.Path }, new StringWriter(), error);

            Assert.Equal(Program.ExitError, code);
            Assert.Contains("Can't find file", error.ToString());
        }

        [Fact]
        public void An_unknown_option_is_an_error()
        {
            var error = new StringWriter();

            var code = Program.Run(new[] { "a.svd", "out", "--chekc" }, new StringWriter(), error);

            Assert.Equal(Program.ExitError, code);
            Assert.Contains("Unknown option --chekc", error.ToString());
        }

        [Fact]
        public void List_names_the_files_and_writes_nothing()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            var svd = input.Write("device.svd", SimpleDevice());
            var target = Path.Combine(output.Path, "not", "created");

            var listed = new StringWriter();
            var code = Program.Run(new[] { svd, target, "--list" }, listed, new StringWriter());

            Assert.Equal(Program.ExitOk, code);
            var prefix = target.Replace('\\', '/') + "/";
            Assert.Equal(
                new[] { "README.md", "device.hpp", "interrupts.hpp", "mmio.hpp", "p.hpp", "vectors.hpp" }.Select(n => prefix + n),
                listed.ToString().Split('\n', StringSplitOptions.RemoveEmptyEntries));
            Assert.DoesNotContain('\r', listed.ToString());
            Assert.False(Directory.Exists(target));
            Assert.Empty(output.Names());
        }

        [Fact]
        public void List_without_a_directory_gives_bare_names()
        {
            using var input = new TempDirectory();
            var svd = input.Write("device.svd", SimpleDevice());

            var listed = new StringWriter();
            var code = Program.Run(new[] { svd, "--list" }, listed, new StringWriter());

            Assert.Equal(Program.ExitOk, code);
            Assert.Equal("README.md\ndevice.hpp\ninterrupts.hpp\nmmio.hpp\np.hpp\nvectors.hpp\n", listed.ToString());
        }

        [Fact]
        public void List_is_exactly_what_a_run_writes()
        {
            using var input = new TempDirectory();
            using var output = new TempDirectory();
            var svd = input.Write("device.svd", SimpleDevice());

            var listed = new StringWriter();
            Program.Run(new[] { svd, "--list" }, listed, new StringWriter());
            Program.Run(new[] { svd, output.Path }, new StringWriter(), new StringWriter());

            Assert.Equal(output.Names(), listed.ToString().Split('\n', StringSplitOptions.RemoveEmptyEntries).OrderBy(n => n, StringComparer.Ordinal));
        }

        [Theory]
        [InlineData("--check")]
        [InlineData("--force")]
        public void List_does_not_go_with_an_option_that_reads_or_writes_the_directory(string option)
        {
            var error = new StringWriter();

            var code = Program.Run(new[] { "a.svd", "out", "--list", option }, new StringWriter(), error);

            Assert.Equal(Program.ExitError, code);
            Assert.Contains("--list writes nothing", error.ToString());
        }

        [Fact]
        public void A_run_without_list_still_needs_its_directory()
        {
            var code = Program.Run(new[] { "a.svd" }, new StringWriter(), new StringWriter());

            Assert.Equal(Program.ExitError, code);
        }

        [Theory]
        [InlineData("DEVICE", "device_2.hpp")]
        [InlineData("INTERRUPTS", "interrupts_2.hpp")]
        [InlineData("MMIO", "mmio_2.hpp")]
        [InlineData("VECTORS", "vectors_2.hpp")]
        public void A_peripheral_does_not_take_the_name_of_another_header(string peripheral, string file)
        {
            var files = Generate(Device(Peripheral(peripheral, 0x1000, SimpleRegister())));

            Assert.Equal(new[] { "README.md", "device.hpp", file, "interrupts.hpp", "mmio.hpp", "vectors.hpp" }.OrderBy(n => n, StringComparer.Ordinal), files.Keys);
        }
    }
